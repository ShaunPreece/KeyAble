#!/usr/bin/env node
/*
 * build-factory-dataset.js  -  Phase 2 step 4 bundler.
 *
 * Reads the per-variant parsed.json files emitted by parse_factory_keymap.js and
 * emits ONE compact `FACTORY_KEYMAPS` object, keyed by numeric USB PID, ready to
 * inline into KeyAble.html.
 *
 * Shape per PID:
 *   {
 *     layers:   [ layer0, layer1, layer2, layer3 ],   // index = layer number
 *                 // each layer: { "row,col": code, ... }  (16-bit factory codes)
 *     encoders: [ enc0, enc1, enc2, enc3 ]             // index = layer number
 *                 // each: [ { ccw: code, cw: code }, ... ]  index = encoderId
 *   }
 *
 * Layer numbering is the app's fixed order (matches the firmware enum):
 *   MAC_BASE=0, MAC_FN=1, WIN_BASE=2, WIN_FN=3.
 *
 * Usage:  node build-factory-dataset.js <parsed.json> [<parsed.json> ...]
 *   Writes DevTools/factory-dataset.generated.js and prints a summary.
 */
'use strict';
const fs = require('fs');
const path = require('path');

// Canonical 4-layer order, used only as the LEGACY fallback for parsed.json
// files produced before the parser emitted a per-model `layerEnum` (the 48
// already-built PIDs). New parses carry their own enum + roles.
const LEGACY_LAYER_INDEX = { MAC_BASE: 0, MAC_FN: 1, WIN_BASE: 2, WIN_FN: 3 };
const LEGACY_LAYER_COUNT = 4;

function die(msg) { console.error('ERROR: ' + msg); process.exit(1); }

const inputs = process.argv.slice(2);
if (!inputs.length) die('usage: node build-factory-dataset.js <parsed.json> [...]');

const dataset = {};      // pidNum -> { layers, encoders }
const summary = [];

for (const file of inputs) {
  const d = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (!d.pid) die(`${file}: no pid`);
  const pidNum = parseInt(d.pid, 16);
  if (Number.isNaN(pidNum)) die(`${file}: bad pid ${d.pid}`);
  if (dataset[pidNum]) die(`duplicate pid ${d.pid} (${file}) - two variants share a PID?`);

  // Per-model enum + roles when the parser emitted them (5-layer boards and any
  // re-parse); otherwise fall back to the canonical 4-layer order so previously
  // built parsed.json stays byte-identical.
  const idx   = (d.layerEnum && d.layerEnum.idx) || LEGACY_LAYER_INDEX;
  const count = (d.layerEnum && d.layerEnum.names && d.layerEnum.names.length) || LEGACY_LAYER_COUNT;

  const layers = Array.from({ length: count }, () => ({}));
  for (const [name, positions] of Object.entries(d.layers || {})) {
    const li = idx[name];
    if (li === undefined) die(`${file}: unexpected layer name ${name}`);
    for (const p of positions) {
      if (p.code == null) die(`${file}: ${name} (${p.row},${p.col}) has no code (token ${p.token})`);
      layers[li][`${p.row},${p.col}`] = p.code;
    }
  }

  const encoders = Array.from({ length: count }, () => []);
  for (const [name, encs] of Object.entries(d.encoders || {})) {
    const li = idx[name];
    if (li === undefined) die(`${file}: unexpected encoder layer ${name}`);
    encoders[li] = encs.map(e => {
      if (e.ccwCode == null || e.cwCode == null) die(`${file}: ${name} encoder missing code`);
      return { ccw: e.ccwCode, cw: e.cwCode };
    });
  }

  // roles are emitted ONLY when non-canonical, so the app falls back to its
  // default 4-layer map for the (unchanged) 48 canonical PIDs.
  const roles = d.roles || null;
  const isCanonical = roles && count === 4 &&
    roles.mac === 0 && roles.macFn === 1 && roles.win === 2 && roles.winFn === 3 && roles.fn2 == null;
  dataset[pidNum] = { layers, encoders, roles: isCanonical ? null : roles };
  const keyCount = layers.reduce((n, m) => n + Object.keys(m).length, 0);
  const encCount = encoders.reduce((n, a) => n + a.length, 0);
  summary.push(`  ${d.pid} (${path.basename(path.dirname(file))}): ${keyCount} keys, ${encCount} encoder dirs`);
}

// Emit as a hex-keyed object literal for human readability (hex key -> same
// numeric property as activeKbd.pid, e.g. 0x0960 === 2400).
const lines = [];
lines.push('// GENERATED by DevTools/build-factory-dataset.js - do not hand-edit.');
lines.push('// Per-model factory keymaps. Keyed by numeric USB PID.');
lines.push('// layers[layerNum]["row,col"] = 16-bit factory code, indexed by the DEVICE');
lines.push('// layer number. Canonical 4-layer boards: Mac=0, MacFn=1, Win=2, WinFn=3.');
lines.push('// Non-canonical boards (5-layer V2 Max / K6 Pro / wired V2) carry a `roles`');
lines.push('// map {mac,win,macFn,winFn,fn2} giving each OS view its real layer index;');
lines.push('// the app falls back to the default 4-layer map when `roles` is absent.');
lines.push('const FACTORY_KEYMAPS = {');
for (const pidNum of Object.keys(dataset).map(Number).sort((a, b) => a - b)) {
  const hex = '0x' + pidNum.toString(16).toUpperCase().padStart(4, '0');
  const entry = dataset[pidNum];
  lines.push(`  ${hex}: {`);
  if (entry.roles) lines.push('    roles: ' + JSON.stringify(entry.roles) + ',');
  lines.push('    layers: [');
  for (const layer of entry.layers) {
    lines.push('      ' + JSON.stringify(layer) + ',');
  }
  lines.push('    ],');
  lines.push('    encoders: [');
  for (const enc of entry.encoders) {
    lines.push('      ' + JSON.stringify(enc) + ',');
  }
  lines.push('    ],');
  lines.push('  },');
}
lines.push('};');
lines.push('');

const outPath = path.join(__dirname, 'factory-dataset.generated.js');
fs.writeFileSync(outPath, lines.join('\n'));

console.log('# wrote ' + outPath);
console.log('# models:');
summary.forEach(s => console.log(s));
console.log('# total PIDs: ' + Object.keys(dataset).length);
