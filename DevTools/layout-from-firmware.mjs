#!/usr/bin/env node
// Writes KEYCHRON_LAYOUTS entries from a keyboard's own firmware, so no matrix position
// or key name is typed by hand. Positions, names and the agreement checks come from
// keyboard-sources.mjs, the same code verify-keyboards.mjs checks with.
//
// Refuses a board whose VIA definition disagrees with its firmware, and a board with no
// VIA definition unless --firmware-only is given.
//
// Usage:
//   node DevTools/layout-from-firmware.mjs entry <pid> <layoutId> [--firmware-only]
//     prints a whole entry, keys in firmware LAYOUT order
//   node DevTools/layout-from-firmware.mjs relabel <layoutId> <pid>
//     prints, as JSON lines, the name changes for an existing entry whose positions are
//     already right; it keeps the entry's key order, so backups made with it stay valid
import { appTables, firmwareBoard, viaBoards, compareViaWithFirmware, keyNaming } from './keyboard-sources.mjs';

const tables = appTables();
const { KEYCHRON_LAYOUTS, KEYBOARD_DB } = tables;
const { nameOf, conflicts } = keyNaming(tables);

function die(msg) { console.error(`ERROR: ${msg}`); process.exit(1); }
const hex = n => '0x' + n.toString(16).toUpperCase().padStart(4, '0');
if (conflicts.length) die(`matching boards name a key differently: ${conflicts.join('; ')}`);

function checkSources(pid, board, firmwareOnly) {
  if (board.error) die(`${hex(pid)}: ${board.error}`);
  const vias = viaBoards(pid);
  if (!vias.length && !firmwareOnly) die(`${hex(pid)} has no VIA definition; pass --firmware-only to use the firmware alone`);
  for (const v of vias) {
    const c = compareViaWithFirmware(board.keys, v);
    if (c.viaOnly.length || c.fwOnly.length > (board.hasEncoder ? 1 : 0) || !c.sameOrder) {
      die(`${hex(pid)}: ${v.source} disagrees with the firmware (VIA-only ${c.viaOnly.join(' ') || 'none'}, firmware-only ${c.fwOnly.join(' ') || 'none'})`);
    }
  }
  return vias;
}

function name(board, i) {
  const n = nameOf(board, i);
  if (n.error) die(n.error);
  return n;
}

const [mode, ...args] = process.argv.slice(2);
if (mode === 'entry') {
  const pid = Number(args[0]), id = args[1];
  if (!pid || !id) die('usage: entry <pid> <layoutId> [--firmware-only]');
  const board = firmwareBoard(pid);
  const vias  = checkSources(pid, board, args.includes('--firmware-only'));
  const size  = board.matrixSize || (vias[0] && vias[0].matrix);
  if (!size) die('no matrix size in the firmware or VIA definition');
  const viaSize = vias[0] && vias[0].matrix;
  if (viaSize && (viaSize.rows !== size.rows || viaSize.cols !== size.cols)) {
    die(`matrix size differs: firmware ${size.rows}x${size.cols}, VIA ${viaSize.rows}x${viaSize.cols}`);
  }
  const quote = s => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  const lines = [
    `  // ${KEYBOARD_DB[pid].name}. Generated by DevTools/layout-from-firmware.mjs from`,
    `  // ${board.source} (${board.macro}); ${vias.length ? `agrees with ${vias.map(v => v.source.split('/').pop()).join(', ')}` : 'no VIA definition exists'}.`,
    `  ${quote(id)}: {`,
    `    name: ${quote(KEYBOARD_DB[pid].name)},`,
    `    pid: ${hex(pid)},`,
    `    rows: ${size.rows},`,
    `    cols: ${size.cols},`,
    '    keys: [',
  ];
  board.keys.forEach((k, i) => {
    const { label, isEncoder } = name(board, i);
    lines.push(`      { label: ${quote(label)}, row: ${k.row}, col: ${k.col}${isEncoder ? ', isEncoder: true' : ''} },`);
  });
  lines.push('    ],', '  },');
  console.log(lines.join('\n'));
} else if (mode === 'relabel') {
  const id = args[0], pid = Number(args[1]);
  const layout = KEYCHRON_LAYOUTS[id];
  if (!layout || !pid) die('usage: relabel <layoutId> <pid>');
  const board = firmwareBoard(pid);
  checkSources(pid, board, args.includes('--firmware-only'));
  const index = new Map(board.keys.map((k, i) => [k.pos, i]));
  if (layout.keys.length !== board.keys.length || layout.keys.some(k => !index.has(`${k.row},${k.col}`))) {
    die(`${id}: positions differ from the firmware, so relabelling is not enough; use entry`);
  }
  for (const k of layout.keys) {
    const { label } = name(board, index.get(`${k.row},${k.col}`));
    if (label !== k.label) console.log(JSON.stringify({ row: k.row, col: k.col, from: k.label, to: label }));
  }
} else {
  die('usage: entry <pid> <layoutId> [--firmware-only] | relabel <layoutId> <pid> [--firmware-only]');
}
